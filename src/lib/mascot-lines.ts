export function pickLine(lines: readonly string[], seed = ""): string {
  const day = new Date().toLocaleDateString("en-CA", { timeZone: "Africa/Cairo" });
  let h = 0;
  for (const ch of `${day}|${seed}`) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return lines[h % lines.length];
}
