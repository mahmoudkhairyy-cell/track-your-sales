function randomFrom(items: string[]): string {
  return items[Math.floor(Math.random() * items.length)];
}

export function pickStatusPhrase(tone: MoodTone, overall: number): string | null {
  if (tone === "behind" || tone === "danger") return randomFrom(BEHIND_PHRASES);
  if (tone !== "ontrack" && tone !== "celebrate") return null;
  const group = ON_TRACK_GROUPS.find((item) => overall >= item.min && overall < item.max);
  return group ? randomFrom(group.phrases) : null;
}
